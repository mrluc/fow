const {test, expect} = require('@playwright/test');
test.use({baseURL: 'http://127.0.0.1:47192'});
test('independent RTS example enforces trails and renders explored versus unknown terrain offline', async ({page}) => {
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.locator('#sector-name')).toHaveText('Base camp');
  await expect(page.locator('.sector-2')).toHaveClass(/fow-nav-uncached/);
  expect(await page.locator('.sector-2 .terrain').evaluate(el => getComputedStyle(el).filter)).toBe('brightness(0)');
  await expect(page.locator('a[href="/sectors/watch"]')).toHaveCount(0);
  await page.locator('.trail[href="/sectors/woods"]').click();
  await expect(page.locator('#sector-name')).toHaveText('Pinewood');
  await page.locator('#survey').click();
  await expect(page.locator('#reports')).toHaveText('1');
  await page.locator('.trail[href="/"]').click();
  await expect(page.locator('.sector-1')).not.toHaveClass(/fow-nav-uncached/);
  const panel = page.locator('[data-fog-of-war-dev-tools]');
  await panel.getByRole('button', {name: /Fog of War/}).click();
  await panel.getByRole('button', {name: 'Pause connection', exact: true}).click();
  const requests=[]; page.on('request', r => requests.push(r.url()));
  await page.locator('.trail[href="/sectors/mill"]').click();
  await expect(page.locator('#sector-name')).toHaveText('Base camp');
  await page.locator('.trail[href="/sectors/woods"]').click();
  await expect(page.locator('#sector-name')).toHaveText('Pinewood');
  await expect(page.locator('#reports')).toHaveText('1');
  await expect(page.locator('#survey')).toBeDisabled();
  await expect(page.locator('.sector-0')).not.toHaveClass(/fow-nav-uncached/);
  await expect(page.locator('a[href="/sectors/mill"]')).toHaveCount(0);
  expect(requests).toEqual([]);
  expect(errors).toEqual([]);
  await page.evaluate(() => Promise.all(document.getAnimations().map(a => a.finished.catch(() => {}))));
  await page.screenshot({path: require('node:path').resolve(__dirname, '../../results/frontier-offline.png'), fullPage: true});
});
