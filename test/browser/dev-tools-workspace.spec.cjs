const {test,expect}=require('@playwright/test');
const tools=page=>page.locator('[data-fog-of-war-dev-tools]');

test('unified timeline records denied and cached navigation in memory, filters and help keep connection controls available',async({page})=>{
  await page.goto('/');
  await page.locator('a[href="/counters/one"]').click();
  await expect(page.locator('#count')).toBeVisible();
  await page.getByRole('link',{name:'‹ Back',exact:true}).click();
  const panel=tools(page);await panel.locator('.launcher').click();
  await expect(panel.getByRole('tab',{name:'Connection',exact:true})).toHaveCount(0);
  await expect(panel.locator('[data-state]')).toHaveText('Live');
  await expect(panel.locator('tr[data-kind="nav"][data-outcome="live"]')).not.toHaveCount(0);
  await panel.getByRole('button',{name:'Disconnect socket',exact:true}).click();
  await page.locator('a[href="/counters/two"]').click();
  const denied=panel.locator('tr[data-kind="nav"][data-outcome="denied"]');
  await expect(denied).toContainText('/counters/two');
  await denied.click();await expect(panel.locator('[data-detail]')).toContainText('No usable saved page');
  await page.locator('a[href="/counters/one"]').click();
  await expect(panel.locator('tr[data-kind="nav"][data-outcome="cached"]')).toContainText('/counters/one');
  const times=await panel.locator('tbody tr').evaluateAll(rows=>rows.map(row=>Number(row.dataset.time)));
  expect(times).toEqual([...times].sort((a,b)=>b-a));
  await panel.getByRole('checkbox',{name:'Nav',exact:true}).uncheck();
  await expect(panel.locator('tr[data-kind="nav"]')).toHaveCount(0);
  await panel.getByRole('checkbox',{name:'Cache',exact:true}).uncheck();
  await expect(panel.locator('[data-empty]')).toBeVisible();
  await panel.getByRole('checkbox',{name:'Nav',exact:true}).check();
  await expect(panel.locator('tr[data-kind="cache"]')).toHaveCount(0);
  await expect(panel.locator('tr[data-outcome="denied"]')).toBeVisible();
  const stored=await page.evaluate(()=>Object.keys(localStorage));
  expect(stored.every(key=>key.startsWith('fog-of-war:page:'))).toBe(true);
  await panel.getByRole('tab',{name:'Help',exact:true}).click();
  await expect(panel.getByRole('heading',{name:'Why this fits LiveView'})).toBeVisible();
  await expect(panel.getByRole('button',{name:'Reconnect',exact:true})).toBeVisible();
  await panel.getByRole('button',{name:'Reconnect',exact:true}).click();
  await expect(page.locator('#count')).toBeVisible();
  await tools(page).locator('.launcher').click();
  await expect(tools(page).locator('tr[data-kind="nav"][data-outcome="denied"], tr[data-kind="nav"][data-outcome="cached"]')).toHaveCount(0);
  expect(await page.evaluate(()=>window.fogOfWar.navigationEvents().every(event=>event.path===location.pathname))).toBe(true);
});

test('pointer docking, panel resize, splitter resize and viewport clamping survive navigation',async({page})=>{
  await page.setViewportSize({width:1200,height:850});await page.goto('/');
  const panel=tools(page);await panel.locator('.launcher').click();
  const drag=async(locator,x,y)=>{const r=await locator.boundingBox();await page.mouse.move(r.x+r.width/2,r.y+r.height/2);await page.mouse.down();await page.mouse.move(x,y,{steps:8});await page.mouse.up()};
  await drag(panel.getByRole('button',{name:'Move developer tools'}),20,20);
  await expect(panel.locator('.tools')).toHaveAttribute('data-dock','top-left');
  const corner=await panel.locator('.panel').boundingBox();expect(corner.width).toBeLessThan(700);
  const handle=await panel.getByRole('separator',{name:'Resize developer tools',exact:true}).boundingBox();
  await drag(panel.getByRole('separator',{name:'Resize developer tools',exact:true}),handle.x+100,handle.y+60);
  const enlarged=await panel.locator('.panel').boundingBox();expect(enlarged.width).toBeGreaterThan(corner.width+70);expect(enlarged.height).toBeGreaterThan(corner.height+30);
  const divider=panel.getByRole('separator',{name:'Resize cache list and details'});
  const oldSplit=Number(await divider.getAttribute('aria-valuenow')),r=await divider.boundingBox();
  await drag(divider,r.x+60,r.y+r.height/2);
  expect(Number(await divider.getAttribute('aria-valuenow'))).toBeGreaterThan(oldSplit);
  await divider.press('ArrowLeft');
  await drag(panel.getByRole('button',{name:'Move developer tools'}),600,835);
  await expect(panel.locator('.tools')).toHaveAttribute('data-dock','bottom');
  expect((await panel.locator('.panel').boundingBox()).width).toBeGreaterThan(1150);
  await page.locator('a[href="/counters/one"]').click();
  await expect(panel.locator('.tools')).toHaveAttribute('data-dock','bottom');
  await page.evaluate(()=>Promise.all(document.getAnimations().filter(a=>a.effect?.getTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{}))));
  await page.setViewportSize({width:375,height:650});
  await expect.poll(async()=>{const b=await panel.locator('.panel').boundingBox();return b.x>=0&&b.x+b.width<=375&&b.y>=0&&b.y+b.height<=650}).toBe(true);
  await page.screenshot({path:require('node:path').resolve(__dirname,'../../results/dev-tools-mobile.png')});
  await page.setViewportSize({width:1200,height:850});
  await page.screenshot({path:require('node:path').resolve(__dirname,'../../results/dev-tools-timeline.png')});
});
