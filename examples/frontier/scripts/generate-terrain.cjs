// Deterministic, dependency-free multi-octave value noise. No image-generation service.
// One continuous world texture avoids seams across the 144 constituent tiles.
const fs = require('node:fs'), path = require('node:path'), zlib = require('node:zlib');
const SIZE=768, TILE=64, SEED=0xF09;
const hash=(x,y)=>{let n=Math.imul(x,374761393)^Math.imul(y,668265263)^SEED;n=Math.imul(n^(n>>>13),1274126177);return ((n^(n>>>16))>>>0)/4294967295};
const smooth=t=>t*t*(3-2*t), lerp=(a,b,t)=>a+(b-a)*t;
function noise(x,y){let a=Math.floor(x),b=Math.floor(y),u=smooth(x-a),v=smooth(y-b);return lerp(lerp(hash(a,b),hash(a+1,b),u),lerp(hash(a,b+1),hash(a+1,b+1),u),v)}
function fbm(x,y){return noise(x/90,y/90)*.5+noise(x/35,y/35)*.27+noise(x/12,y/12)*.15+noise(x/4,y/4)*.08}
const pixels=Buffer.alloc(SIZE*(SIZE*4+1));
for(let y=0;y<SIZE;y++)for(let x=0;x<SIZE;x++){
 const n=fbm(x,y), grain=(hash(x,y)-.5)*14;
 // Thin wandering footpaths through grassy clearings, not a grid of beige squares.
 const roadX=112+Math.sin(y/128)*48+y*.61;
 const roadY=120+Math.sin(x/150)*60+x*.57;
 const d=Math.min(Math.abs(x-roadX),Math.abs(y-roadY));
 const edge=noise(x/15,y/15)*8;
 const dirt=Math.max(0,Math.min(1,(20+edge-d)/10));
 const shade=grain+(n-.5)*38;
 const grass=[57+shade*.75,83+shade,37+shade*.5];
 const soil=[125+shade,99+shade*.85,61+shade*.6];
 const i=y*(SIZE*4+1)+1+x*4;
 for(let c=0;c<3;c++)pixels[i+c]=Math.round(Math.max(0,Math.min(255,lerp(grass[c],soil[c],dirt))));
 // Sparse pale grass tips/pebbles; small enough to read as texture, not confetti.
 if(hash(x+5000,y)> .992){pixels[i]+=16;pixels[i+1]+=15;pixels[i+2]+=9}
 pixels[i+3]=255;
}
function crc32(buf){let c=0xffffffff;for(const b of buf){c^=b;for(let i=0;i<8;i++)c=(c>>>1)^((c&1)?0xedb88320:0)}return (c^0xffffffff)>>>0}
function chunk(type,data){const t=Buffer.from(type),b=Buffer.alloc(data.length+12);b.writeUInt32BE(data.length);t.copy(b,4);data.copy(b,8);b.writeUInt32BE(crc32(Buffer.concat([t,data])),data.length+8);return b}
const ihdr=Buffer.alloc(13);ihdr.writeUInt32BE(SIZE);ihdr.writeUInt32BE(SIZE,4);ihdr[8]=8;ihdr[9]=6;
const out=path.resolve(__dirname,'../priv/static/images/terrain.png');
fs.writeFileSync(out,Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]),chunk('IHDR',ihdr),chunk('IDAT',zlib.deflateSync(pixels,{level:9})),chunk('IEND',Buffer.alloc(0))]));
let css='/* Generated by scripts/generate-terrain.cjs. Each sector contains 3 × 3 tiles. */\n';
for(let lat=0;lat<4;lat++)for(let lon=0;lon<4;lon++){
 const depth = 104 + (lat + lon) * 34;
 css+=`.at-${lat}-${lon} { left: ${320+(lon-lat)*68}px; top: ${depth}px; --tile-depth: ${depth}; }\n`;
 for(let i=0;i<9;i++) css+=`.at-${lat}-${lon} .tile-${i} { background-position: ${-(lon*3+i%3)*32}px ${-(lat*3+Math.floor(i/3))*32}px; }\n`;
}
fs.writeFileSync(path.resolve(__dirname,'../priv/static/css/terrain.css'),css);
console.log(`Wrote ${SIZE}×${SIZE} terrain atlas, 144 continuous noise tiles, seed ${SEED}`);
